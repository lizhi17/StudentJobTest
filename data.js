    portrait:portrait, why:why, evidence:evidence,
    pros:pros, cons:cons, gap:gapText, tips:tips, kw:kw,
    jobs:jobs, mine:mine,
    fitWhy:"这 5 个岗位的共同点是：和你「"+TS.name+"」的特质高度一致——"+TS.fitWhyExt,
    mineWhy:"这些岗位的共同点是：它们会持续消耗你在「"+LS.name+"」上的能量。",
