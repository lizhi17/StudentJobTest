/* 优先级：手写 MAJOR_FIT > 自动生成（按人格偏好挑岗位 + 生成说明） */
function buildMajorFit(){
  const out={};
  // 收集所有专业
  const allSubs={};
  for(const gk in MAJOR_GROUPS){
    const g=MAJOR_GROUPS[gk];
    for(const sk in g.subs) allSubs[sk]=g.subs[sk];
  }
  for(const sk in allSubs){
    const sub=allSubs[sk];
    for(const p of ["A","B","C","D","E","F"]){
      const key=p+sk;
      if(MAJOR_FIT[key]){out[key]=MAJOR_FIT[key];continue}
      // 自动挑选：用岗位气质 + 人格关键词打分
      const rule=PERSONA_RULE[p];
      const scored=sub.jobs.map(j=>{
        let s=0;
        for(const t in JOB_TRAIT){
          if(j.indexOf(t)>=0){ if(TRAIT_PERSONA[t]===p) s+=3; else s-=1; }
        }
        for(const kw of rule.prefer){ if(j.indexOf(kw)>=0) s+=2; }
        for(const kw of rule.avoid){ if(j.indexOf(kw)>=0) s-=3; }
        return {j:j,s:s};
      }).sort((a,b)=>b.s-a.s);
      const pick=scored.slice(0,5).map(x=>x.j);
      // 岗位池不足 5 个时，用专业池里剩下的补齐
      if(pick.length<5){
        for(const j of sub.jobs){ if(pick.length>=5)break; if(pick.indexOf(j)<0)pick.push(j); }
      }
      // 说明里带上专业名，避免所有专业看起来一模一样
      const note=rule.note.replace("在你的专业里","在「"+sub.name+"」里");
      out[key]={pick:pick,note:note};
    }
  }
  return out;
}
const MAJOR_FIT_ALL=buildMajorFit();

